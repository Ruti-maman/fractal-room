import { useEffect, useRef, useState, type ReactNode } from "react";
import { playWhoosh } from "../lib/tapFeedback";

/*
 * ============================================================================
 *  המעבר בין שלבים
 * ============================================================================
 *
 *  ----------------------------------------------------------------------
 *  שלוש גרסאות שנפסלו, וכל אחת מסיבה אחרת
 *  ----------------------------------------------------------------------
 *    1. **פריחת אור** - כתם טורקיז שהתפשט ונעלם. אין לו כיוון ואין לו
 *       צורה, והוא נקרא כתקלת תצוגה ולא כמעבר.
 *    2. **תריס להבים** - שבעה פסים אלכסוניים שסגרו את המסך. כיוון היה
 *       לו, אבל פס רחב שחוצה מסך 65" נקרא כחיתוך.
 *    3. **רשת מעוינים** - שישים חלקיקים שצצו מפוזר. יותר מדי תנועה;
 *       זה נקרא כרעש.
 *
 *  ----------------------------------------------------------------------
 *  המסקנה
 *  ----------------------------------------------------------------------
 *  המשותף לשלושתן: כולן ניסו **להיראות**. אבל מעבר בין שלבים קורה עשר
 *  פעמים בסדנה, ותפקידו להחליק את הקפיצה - לא להופיע בעצמו. אפקט שמושך
 *  תשומת לב הוא נחמד פעם אחת ומעצבן בפעם החמישית.
 *
 *  לכן כאן: החשכה רכה שעולה ויורדת, גל אור טורקיז אחד שעובר דרכה,
 *  והמסך החדש נמוג פנימה מתחתיה. חצי שנייה, בלי צורות ובלי חלקיקים.
 *  זה מה שמשחקים מלוטשים עושים בין סצנות, והסיבה שלא שמים לב לזה היא
 *  בדיוק הסיבה שזה עובד.
 *
 *  ----------------------------------------------------------------------
 *  אזהרה למי שיגע בזה
 *  ----------------------------------------------------------------------
 *  אנימציית הכניסה של **עוטף התוכן** היא opacity בלבד, בכוונה גמורה.
 *  `transform` עליו היה הופך אותו לנקודת הייחוס של כל `position: fixed`
 *  שבתוכו - הטיימר, מד ההתקדמות ורצועת ההשראות היו נצמדים לתוכן במקום
 *  למסך. מלכודת שכבר נפלנו בה פעמיים (ראו Stage3Associations ו-ClipPlayer).
 *  כל התנועה שמורה לשכבת ההחשכה, שהיא `fixed` ועומדת בפני עצמה.
 */

const FADE_MS = 560;

interface Props {
  /** מספר השלב. שינוי שלו הוא מה שמפעיל את המעבר. */
  stageKey: number;
  children: ReactNode;
}

function StageTransition({ stageKey, children }: Props) {
  const previous = useRef(stageKey);
  const [runId, setRunId] = useState(0);

  useEffect(() => {
    if (previous.current === stageKey) return;
    previous.current = stageKey;
    setRunId((n) => n + 1);
    playWhoosh();
    const t = window.setTimeout(() => setRunId(0), FADE_MS + 60);
    return () => window.clearTimeout(t);
  }, [stageKey]);

  return (
    <>
      {/* התוכן נמוג פנימה בזמן שההחשכה יורדת, כך שהמסך החדש כבר שם
          כשהיא נעלמת - ולא "קופץ" אחריה. */}
      <div key={stageKey} style={{ animation: "page-fade 520ms 120ms var(--ds-ease) both" }}>
        {children}
      </div>

      {runId > 0 && <div key={runId} className="stage-fade" aria-hidden="true" />}
    </>
  );
}

export default StageTransition;
