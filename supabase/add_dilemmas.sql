--   "ספריית דילמות, מסך ראשוני שמרוכזים בו כל הדילמות, ויש אפשרות לבחור את
--    הדילמה שתוביל את הסדנה."
--
-- כל דילמה שייכת לתוכנית, ויש לה את כל מה שהסדנה צריכה ממנה:
--   video_url    - הסרטון שצופים בו בשלב 2
--   summary      - המשפט הקצר במרכז השמש בשלב 3
--   profile_text - התיאור המלא שמסמנים עליו חוזקות וחסמים בשלב 4 (ומשמש את ה-AI)
-- ההפעלה (workshops.dilemma_id) אומרת איזו דילמה נבחרה. כשאין בחירה - הסדנה
-- נופלת בחזרה לטקסטים שבתוכן השלבים, כמו קודם.
--
-- להריץ פעם אחת (SQL Editor, או: npx supabase db query --remote -f supabase/add_dilemmas.sql).

create table if not exists dilemmas (
  id uuid primary key default gen_random_uuid(),
  program_id uuid not null references programs(id) on delete cascade,
  sort_order int not null default 0,
  title text not null,
  summary text,
  profile_text text,
  video_url text,
  created_at timestamptz not null default now()
);

alter table dilemmas enable row level security;
-- אותה מדיניות פתוחה כמו בשאר הטבלאות (ראו schema.sql)
drop policy if exists "public read/write" on dilemmas;
create policy "public read/write" on dilemmas for all using (true) with check (true);

alter table workshops add column if not exists dilemma_id uuid references dilemmas(id) on delete set null;

